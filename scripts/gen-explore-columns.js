#!/usr/bin/env node
/*
 * Regenerates utility/exploreColumns.generated.ts from the database: for every
 * production.vw_explore_* view, the GraphQL field name (PostGraphile camelCase) → SQL column.
 * The /data tables use it to turn grid fields into explore_<table>(filters) keys and orderBy
 * enum values (see db/migrations/2026_09_23_1_explorer_filters.sql).
 *
 *   node scripts/gen-explore-columns.js      (reads DATABASE_URL from .env)
 */
const fs = require("fs");
const path = require("path");
const { Client } = require("pg");

require("dotenv").config({ path: path.join(__dirname, "..", ".env") });

// PostGraphile's inflector: lodash-style camelCase of the snake_case name.
const camel = (s) =>
	s
		.split(/[^A-Za-z0-9]+/)
		.filter(Boolean)
		.flatMap((w) => w.split(/(?<=[a-z])(?=[0-9])|(?<=[0-9])(?=[a-z])/i))
		.map((w, i) => (i === 0 ? w.toLowerCase() : w[0].toUpperCase() + w.slice(1).toLowerCase()))
		.join("");

(async () => {
	const client = new Client({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false } });
	await client.connect();
	const { rows } = await client.query(`
		SELECT table_name, column_name
		FROM information_schema.columns
		WHERE table_schema = 'production' AND table_name LIKE 'vw\\_explore\\_%'
		ORDER BY table_name, ordinal_position`);
	await client.end();

	const byView = {};
	for (const r of rows) (byView[r.table_name] ??= {})[camel(r.column_name)] = r.column_name;

	const body = Object.entries(byView)
		.map(([view, cols]) => `\t${view}: {\n${Object.entries(cols).map(([k, v]) => `\t\t${k}: "${v}",`).join("\n")}\n\t},`)
		.join("\n");
	const out = `// GENERATED by scripts/gen-explore-columns.js — do not edit by hand.\n// GraphQL field (camelCase) → SQL column for each production.vw_explore_* view.\nexport const exploreColumns: Record<string, Record<string, string>> = {\n${body}\n};\n`;
	fs.writeFileSync(path.join(__dirname, "..", "utility", "exploreColumns.generated.ts"), out);
	console.log(`wrote ${Object.keys(byView).length} views`);
})().catch((e) => {
	console.error(e.message);
	process.exit(1);
});
